/**
 * Copy the season engine's multiple-choice banks into the browser's dev grader.
 *
 * The engine is authoritative. `src/lib/academy/beginner.ts` and
 * `intermediate.ts` over there hold the questions, and the engine's grader is
 * what decides a real completion. `src/components/Academy/lib/questions.js` here
 * is a mirror, so a lesson page still works when the engine is not running.
 *
 * Two copies of 50-odd questions drift. They have drifted before. So this script
 * extracts the banks out of the engine source and writes the mirror, rather than
 * asking anyone to keep them in step by hand.
 *
 *   pnpm banks:sync     rewrite the mirror from the engine
 *   pnpm banks:check    fail if the two disagree (runs inside copy:check)
 *
 * If the engine repo is not checked out beside this one, both modes say so and
 * exit 0. Someone editing docs prose should not be blocked on that.
 */
import fs from "node:fs";
import path from "node:path";

const HERE = path.resolve(import.meta.dirname, "..");
const ENGINE = path.resolve(HERE, "..", "Alchemix-Seasons", "src", "lib", "academy");
const MIRROR = path.join(HERE, "src", "components", "Academy", "lib", "questions.js");

const check = process.argv.includes("--check");

if (!fs.existsSync(ENGINE)) {
  console.log("The season engine is not checked out beside this repo; nothing to sync.");
  process.exit(0);
}

/**
 * Walk forward from an opening bracket to its match, skipping anything inside a
 * string. The banks are plain array and object literals, so nothing cleverer is
 * needed, but an apostrophe inside an option would break naive counting.
 */
function matchBracket(src, start) {
  const open = src[start];
  const close = open === "[" ? "]" : "}";
  let depth = 0;
  let quote = null;
  for (let i = start; i < src.length; i += 1) {
    const c = src[i];
    if (quote) {
      if (c === "\\") i += 1;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === open) depth += 1;
    else if (c === close) {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  throw new Error("unbalanced bracket");
}

/** Every `choiceLesson("id", "title", [ ... ])` in a file, in source order. */
function banksIn(file) {
  const src = fs.readFileSync(file, "utf8").split("\r\n").join("\n");
  const out = [];
  const call = /choiceLesson\(\s*"([^"]+)"\s*,\s*"[^"]*"\s*,\s*/g;
  let m;
  while ((m = call.exec(src)) !== null) {
    const openAt = src.indexOf("[", m.index + m[0].length - 1);
    const closeAt = matchBracket(src, openAt);
    out.push([m[1], src.slice(openAt, closeAt + 1)]);
    call.lastIndex = closeAt;
  }
  return out;
}

const banks = [
  ...banksIn(path.join(ENGINE, "beginner.ts")),
  ...banksIn(path.join(ENGINE, "intermediate.ts")),
];

if (!banks.length) {
  console.error("Found no choice banks in the engine. Has choiceLesson been renamed?");
  process.exit(1);
}

/* Re-indent the engine's bank body by two spaces: it sits one level deeper here,
   inside the QUESTIONS object rather than as a call argument. */
const indent = (body) =>
  body
    .split("\n")
    .map((line, i) => (i === 0 || line === "" ? line : "  " + line))
    .join("\n");

const rendered = banks.map(([id, body]) => `  ${JSON.stringify(id)}: ${indent(body)},`).join("\n\n");

const HEADER = `/**
 * The multiple-choice banks for both tracks, mirrored for local development.
 *
 * GENERATED by scripts/sync-academy-banks.mjs. Edit the questions in the season
 * engine, at src/lib/academy/beginner.ts and intermediate.ts, then run
 * \`pnpm banks:sync\`. \`pnpm copy:check\` fails if the two ever disagree.
 *
 * The engine is authoritative: its grader is what decides a real completion.
 * This copy exists so a lesson page still works when the engine is not running,
 * which is the difference between someone being able to edit Academy prose and
 * not. Everything it feeds is issued as an inert \`local:\` token.
 */

export const QUESTIONS = {
${rendered}
};
`;

const FOOTER = `
/**
 * The same deterministic shuffle the engine uses, so a locally generated question
 * behaves the way the deployed one does.
 *
 * Returns display position to original index.
 */
export function permutation(n, seed) {
  const order = Array.from({ length: n }, (_, i) => i);

  let state = (Math.abs(Math.trunc(seed)) % 2147483647) + 1;
  const next = () => {
    state = (state * 1664525 + 1013904223) % 4294967296;
    return state / 4294967296;
  };

  for (let i = n - 1; i > 0; i -= 1) {
    const j = Math.floor(next() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}
`;

const wanted = HEADER + FOOTER;

const existing = fs.existsSync(MIRROR) ? fs.readFileSync(MIRROR, "utf8") : "";
const crlf = existing.includes("\r\n");
const current = crlf ? existing.split("\r\n").join("\n") : existing;

if (current === wanted) {
  console.log(`Question banks are in step: ${banks.length} lessons.`);
  process.exit(0);
}

if (check) {
  console.error("The docs question bank has drifted from the engine. Run `pnpm banks:sync`.");
  process.exit(1);
}

fs.writeFileSync(MIRROR, crlf ? wanted.split("\n").join("\r\n") : wanted);
console.log(`Synced ${banks.length} question banks: ${banks.map(([id]) => id).join(", ")}`);
